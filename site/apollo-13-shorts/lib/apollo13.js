/* apollo13.js: the Apollo 13 shorts' own pieces, loaded after shorts.js and the episode's img/chNN-art.js. Pure
   functions of the beat clock, like the kit. Episodes use these and do not edit this file; episode-only code goes in the
   episode's page. The series' choices are written down in books/apollo-13/shorts/SERIES.md.

   seriesCard(s, t0, n, tLit)        the three episodes as upright tiles, n (1-3) lit at tLit (a wordless 2 s beat)
   endCard(s, t0, n, music, push)    APOLLO 13 · n TITLE, the episode's tile and the credit line (a wordless 3 s beat);
                                     music: the episode's recording, e.g. 'Holst, Jupiter · U.S. Air Force Band';
                                     push: the tile's slow push in s from t0 + .5 (default 3.2), so it ends with the beat
   metClock(g, keys, { x, y })       the mission clock chip: keys [[t, minutes after launch], ...], held at the first
                                     key, counting between keys; shown as H:MM ('55:54', '141:30'), amber on the ground
   met(h, m)                         minutes after launch, for metClock keys: met(55, 54)
   Colours are shorts.js's: DARK the deep blue ground, LIGHT the ink, MUTED the captions, MARK the amber. */
'use strict';
const EP_TITLES = ['The Lifeboat', 'Two Pushes', 'The Adapter'];
const EP_PICS = ['ch01-lm-aquarius', 'ch01-moon-far-side', 'ch01-scrubber-in-aquarius'];
const EP_W = 220, EP_H = 390, EP_X = [210, 450, 690];

function epTile(s, i, x, y) {
  const c = G(s, { x, y, o: 0 });
  rect(c, -EP_W / 2 - 4, -EP_H / 2 - 4, EP_W + 8, EP_H + 8, { rx: 16, fill: '#081626' });
  clipImg(c, EP_PICS[i], -EP_W / 2, -EP_H / 2, EP_W, EP_H, 12);
  rect(c, -EP_W / 2, EP_H / 2 - 70, EP_W, 70, { fill: DARK, opacity: .82 });
  T(c, String(i + 1), { x: -EP_W / 2 + 16, y: -EP_H / 2 + 62, size: 64, fill: LIGHT, font: SANS, weight: 600 });
  const title = EP_TITLES[i].toUpperCase(), size = Math.min(36, 36 * (EP_W - 24) / inkW(title, 36));
  T(c, title, { x: 0, y: EP_H / 2 - 24, size, fill: LIGHT, font: SANS, weight: 600, anchor: 'middle' });
  return c;
}

function seriesCard(s, t0, n, tLit) {
  word(s, 'Apollo 13', CX, 400, t0, { size: 130, fill: LIGHT });
  const sub = T(s, 'THREE SHORT FILMS', { x: CX, y: 470, size: 34, fill: MUTED, font: SANS, weight: 500, anchor: 'middle', o: 0 });
  sub.setAttribute('letter-spacing', '.14em'); show(sub, t0 + .1, .25, lin);
  sfx(BEAT_ID, t0, 'thud', 1);
  const y = 800;
  const tiles = EP_X.map((x, i) => { const c = epTile(s, i, x, y); put(c, { y: y + 80 }); tw(c, { o: 1, y }, t0 + .2 + i * .1, .3, out); return c; });
  const x = EP_X[n - 1];
  const rim = put(rect(s, x - EP_W / 2 - 10, y - EP_H / 2 - 10, EP_W + 20, EP_H + 20, { rx: 22, fill: 'none', stroke: MARK, 'stroke-width': 9 }), { o: 0 });
  show(rim, tLit, .15, lin); sfx(BEAT_ID, tLit, 'tick', 1.2);
  tiles.forEach((c, i) => { if (i !== n - 1) tw(c, { o: .3 }, tLit, .3); });
  return tiles;
}

function endCard(s, t0, n, music, push = 3.2) {
  word(s, 'Apollo 13', CX, 330, t0, { size: 120, fill: LIGHT });
  const c = epTile(s, n - 1, CX, 690);
  put(c, { s: .9 }); tw(c, { o: 1, s: 1.1 }, t0 + .1, .4, out);
  tw(c, { s: 1.22 }, t0 + .5, push, lin);   // a slow push, so the card is not a still frame
  const lines = ['Story: Wikipedia, “Apollo 13” (rev. 1386441839), CC BY-SA 4.0',
    'Pictures and the recording: NASA, public domain', `Music: ${music}, public domain`];
  lines.forEach((l, i) => {
    const size = Math.min(30, 30 * 700 / inkW(l, 30, SERIF, 400));
    const e = T(s, l, { x: CX, y: 1050 + i * 48, size, fill: MUTED, font: SERIF, weight: 400, anchor: 'middle', o: 0 });
    e.setAttribute('font-style', 'italic'); show(e, t0 + .4 + i * .12, .3, lin);
  });
}

const met = (h, m) => h * 60 + m;
const metText = min => `${Math.floor(min / 60)}:${String(Math.floor(min % 60)).padStart(2, '0')}`;
function metClock(g, keys, { x = CX, y = 215 } = {}) {
  const e = G(g, { x, y, o: 0 });
  rect(e, -175, -80, 350, 132, { rx: 12, fill: DARK, opacity: .86 });
  const lab = T(e, 'HOURS AFTER LAUNCH', { x: 0, y: -44, size: 26, fill: MUTED, font: SANS, weight: 500, anchor: 'middle' });
  lab.setAttribute('letter-spacing', '.12em');
  const num = T(e, metText(keys[0][1]), { x: 0, y: 36, size: 84, fill: MARK, font: SANS, weight: 600, anchor: 'middle' });
  if (keys[0][0] <= .01) put(e, { o: 1 }); else show(e, keys[0][0], .2, lin);
  keys.slice(1).forEach(([t, v], i) => {
    const [ta, va] = keys[i];
    prog(q => { num.textContent = metText(va + (v - va) * q); }, ta, Math.max(.01, t - ta), out);
    if (v !== va) sfx(BEAT_ID, ta, 'tick', .6);
  });
  return e;
}
